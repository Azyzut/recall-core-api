import { NextResponse } from 'next/server';
import { createUser, findUserByEmail } from '@/lib/services/user';
import { linkAnonymousDiscoveries } from '@/lib/services/auth-redirect';

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const { email, password } = body;

    // Validation
    if (!email || !password) {
      return NextResponse.json(
        { error: 'Email and password are required' },
        { status: 400 }
      );
    }

    if (password.length < 8) {
      return NextResponse.json(
        { error: 'Password must be at least 8 characters' },
        { status: 400 }
      );
    }

    // Check if email is valid format
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      return NextResponse.json(
        { error: 'Invalid email format' },
        { status: 400 }
      );
    }

    // Check if user already exists
    const existingUser = await findUserByEmail(email);
    if (existingUser) {
      return NextResponse.json(
        { error: 'An account with this email already exists' },
        { status: 409 }
      );
    }

    // Create user
    const user = await createUser({ email, password });

    // Link anonymous discoveries if email matches a company's contactEmail
    const linked = await linkAnonymousDiscoveries(user.id, email);

    return NextResponse.json({
      success: true,
      user: {
        id: user.id,
        email: user.email,
      },
      linked, // True if we linked prior anonymous discoveries
    });
  } catch (error) {
    console.error('Registration error:', error);
    return NextResponse.json(
      { error: 'Failed to create account. Please try again.' },
      { status: 500 }
    );
  }
}
